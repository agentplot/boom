// The diagrams' check, and the README's copy of the start page's.
//
//   bun scripts/diagrams.ts --check   every diagram, both layouts: well formed,
//                                     titled and described, its ids its own,
//                                     and each text inside the box it sits in;
//                                     and docs/diagrams/boom.svg is what the
//                                     site draws now (site:test)
//   bun scripts/diagrams.ts --write   writes docs/diagrams/boom.svg: the hero,
//                                     standalone, with its own palette, light
//                                     or dark by the reader's setting
//
// A text's width is estimated from its characters and its class's font, so
// the check is a guard against a label that runs out of its box, never a
// measure of the rendered page; the screenshots (scripts/shots.mjs) are.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { diagrams } from "../src/diagrams";
import { hero } from "../src/diagrams/hero";
import type { Layout } from "../src/diagrams/kit";

const readme = resolve(dirname(fileURLToPath(import.meta.url)), "../../docs/diagrams/boom.svg");
const banner =
  "<!-- Generated by site/scripts/diagrams.ts from site/src/diagrams/hero.ts; edit those, not this file. -->\n";
const standalone = () => banner + hero("wide", { id: "bm", standalone: true });

if (process.argv.includes("--write")) {
  writeFileSync(readme, standalone());
  console.log(`wrote ${readme}`);
  process.exit(0);
}

const problems: string[] = [];

// Font size and average advance, in ems, by class. IBM Plex Mono advances
// 0.6 em a character; Plex Sans averages under 0.45 em in these labels, so
// 0.5 leaves room, and a little more for bold and for the spaced capitals
// of a heading.
const SIZE: Record<string, number> = { h: 17, sm: 13, xs: 11.5, xxs: 10.5, hd: 11, badget: 11.5 };
const advance = (classes: Set<string>) => {
  if (classes.has("mono")) return 0.6;
  if (classes.has("hd")) return 0.68;
  return classes.has("b") || classes.has("h") || classes.has("chipt") || classes.has("badget")
    ? 0.54
    : 0.5;
};

interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

const attr = (tag: string, name: string) => {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : undefined;
};
const unentity = (s: string) =>
  s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

function check(name: string, layout: Layout, svg: string) {
  const where = `${name} (${layout})`;
  const root = svg.match(/class="([a-z]+)-root/);
  if (!root) {
    problems.push(`${where}: no root class`);
    return;
  }
  const p = root[1];
  const box = svg.match(/viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"/);
  if (!box) {
    problems.push(`${where}: no view box`);
    return;
  }
  const W = Number(box[1]);
  const H = Number(box[2]);

  // Well formed: every element closes, in order. The style holds no tags.
  const body = svg.replace(/<style>[\s\S]*?<\/style>/g, "").replace(/<!--[\s\S]*?-->/g, "");
  const stack: string[] = [];
  for (const m of body.matchAll(/<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g)) {
    const [, close, tag, , self] = m;
    if (self) continue;
    if (close) {
      const open = stack.pop();
      if (open !== tag) problems.push(`${where}: </${tag}> closes <${open ?? "nothing"}>`);
    } else stack.push(tag);
  }
  if (stack.length) problems.push(`${where}: <${stack.join("> <")}> left open`);

  // Titled and described, for a reader who cannot see it.
  const title = svg.match(/<title id="[^"]+">([^<]+)<\/title>/);
  const desc = svg.match(/<desc id="[^"]+">([^<]+)<\/desc>/);
  if (!title || title[1].trim().length < 8) problems.push(`${where}: no title`);
  if (!desc || desc[1].trim().length < 80) problems.push(`${where}: no description worth reading`);

  // Its ids are its own: each once, and each under its prefix.
  const ids = [...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    if (!id.startsWith(`${p}-`)) problems.push(`${where}: id ${id} outside its prefix ${p}-`);
  }
  if (new Set(ids).size !== ids.length) problems.push(`${where}: an id twice`);

  // Each text inside the smallest box its anchor sits in, the view box at
  // the least.
  const rects: Rect[] = [];
  for (const m of body.matchAll(/<rect\b[^>]*>/g)) {
    const t = m[0];
    const w = Number(attr(t, "width"));
    const h = Number(attr(t, "height"));
    if (!w || !h || h < 14) continue;
    rects.push({ x: Number(attr(t, "x") ?? 0), y: Number(attr(t, "y") ?? 0), w, h });
  }
  for (const m of body.matchAll(/<text\b([^>]*)>([\s\S]*?)<\/text>/g)) {
    const tag = m[1];
    const words = unentity(m[2].replace(/<[^>]+>/g, ""));
    if (!words.trim()) continue;
    const classes = new Set(
      (attr(` ${tag}`, "class") ?? "")
        .split(/\s+/)
        .filter(Boolean)
        .map((c) => c.slice(p.length + 1)),
    );
    const size = [...classes].map((c) => SIZE[c]).find(Boolean) ?? 13;
    const width = words.length * size * advance(classes);
    const x = Number(attr(` ${tag}`, "x") ?? 0);
    const y = Number(attr(` ${tag}`, "y") ?? 0);
    const anchor = attr(` ${tag}`, "text-anchor") ?? "start";
    const left = anchor === "middle" ? x - width / 2 : anchor === "end" ? x - width : x;
    const right = left + width;
    const inside = rects
      .filter((r) => x >= r.x && x <= r.x + r.w && y - size * 0.35 >= r.y && y <= r.y + r.h)
      .sort((a, b) => a.w * a.h - b.w * b.h)[0] ?? { x: 0, y: 0, w: W, h: H };
    const slack = 2;
    if (left < inside.x - slack || right > inside.x + inside.w + slack) {
      problems.push(
        `${where}: "${words}" runs ${Math.round(left < inside.x ? inside.x - left : right - inside.x - inside.w)}px out of the box at ${inside.x},${inside.y} (${inside.w} wide)`,
      );
    }
    if (y - size * 0.75 < 0 || y > H) problems.push(`${where}: "${words}" outside the view box`);
  }
}

for (const [name, draw] of Object.entries(diagrams)) {
  for (const layout of ["wide", "narrow"] as const) check(name, layout, draw(layout));
}

// The README's copy is the one the site draws now.
let current = "";
try {
  current = readFileSync(readme, "utf8");
} catch {
  problems.push(`${readme} is missing: bun scripts/diagrams.ts --write`);
}
if (current && current !== standalone()) {
  problems.push(`${readme} is not what the site draws now: bun scripts/diagrams.ts --write`);
}

if (problems.length) {
  for (const problem of problems) console.error(problem);
  console.error(`diagrams: ${problems.length} problems`);
  process.exit(1);
}
console.log(`diagrams: ${Object.keys(diagrams).length} diagrams, both layouts, hold together`);
